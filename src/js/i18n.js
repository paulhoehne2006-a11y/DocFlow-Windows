const lang = (navigator.language || 'de').toLowerCase().startsWith('de') ? de : en;

export function t(key, ...args) {
  const v = lang[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}

export function relativeTime(ms) {
  const diff = Math.max(0, Date.now() - ms) / 1000;
  if (diff < 60) return t('justNow');
  if (diff < 3600) return t('minutesAgo', Math.floor(diff / 60));
  if (diff < 86400) return t('hoursAgo', Math.floor(diff / 3600));
  if (diff < 86400 * 14) return t('daysAgo', Math.floor(diff / 86400));
  return new Date(ms).toLocaleDateString();
}
