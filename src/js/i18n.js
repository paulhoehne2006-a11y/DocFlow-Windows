let currentPref = 'auto';
let activeDict = detectDict();

function detectDict() {
  const nav = typeof navigator !== 'undefined' ? (navigator.language || 'de') : 'de';
  return nav.toLowerCase().startsWith('de') ? de : en;
}

export function setLanguage(pref = 'auto') {
  currentPref = pref;
  if (pref === 'de') activeDict = de;
  else if (pref === 'en') activeDict = en;
  else activeDict = detectDict();
  if (typeof document !== 'undefined') {
    document.documentElement.lang = activeDict === de ? 'de' : 'en';
  }
}

export function getLanguage() {
  return currentPref;
}

export function getEffectiveLanguage() {
  return activeDict === de ? 'de' : 'en';
}

export function t(key, ...args) {
  const v = activeDict[key] ?? de[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}

export function relativeTime(ms) {
  if (!ms) return '—';
  const diff = Math.max(0, Date.now() - ms) / 1000;
  if (diff < 60) return t('justNow');
  if (diff < 3600) return t('minutesAgo', Math.floor(diff / 60));
  if (diff < 86400) return t('hoursAgo', Math.floor(diff / 3600));
  if (diff < 86400 * 14) return t('daysAgo', Math.floor(diff / 86400));
  const locale = getEffectiveLanguage() === 'de' ? 'de-DE' : 'en-US';
  return new Date(ms).toLocaleDateString(locale);
}
